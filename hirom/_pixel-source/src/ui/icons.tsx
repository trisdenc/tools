export function PixelIcon({ rows, size = 16 }: { rows: string[]; size?: number }) {
  const rects: JSX.Element[] = [];
  rows.forEach((row, y) =>
    [...row].forEach((ch, x) => {
      if (ch === '#') rects.push(<rect key={`${x},${y}`} x={x} y={y} width={1} height={1} />);
    }),
  );
  return (
    <svg width={size} height={size} viewBox="0 0 8 8" shapeRendering="crispEdges" fill="currentColor" aria-hidden>
      {rects}
    </svg>
  );
}

export const ToolIcon = ({ tool }: { tool: ToolId }) => <PixelIcon rows={ICONS[tool]} />;

